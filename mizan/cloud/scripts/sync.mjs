// Copies the shared Mizan code into lib/ so the cloud service deploys on its own.
//   node scripts/sync.mjs          write the copies
//   node scripts/sync.mjs --check  fail if a copy is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const here = (p) => fileURLToPath(new URL(p, import.meta.url))
const repo = (p) => here(`../../../${p}`)

const HEADER = '// Generated by scripts/sync.mjs from the Mizan repo. Do not edit by hand.\n'

const SC_LIST = 'mizan/data/sc-shariah-list-2026-05-29.json'

const copies = [
  {
    out: here('../lib/forecast.js'),
    build: () => HEADER + ts.transpileModule(readFileSync(repo('ui/src/mizan/forecast.ts'), 'utf8'), {
      compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 },
    }).outputText,
  },
  { out: here('../lib/sc-list.json'), build: () => readFileSync(repo(SC_LIST), 'utf8') },
  { out: here('../lib/bars.js'), build: () => HEADER + readFileSync(repo('api/bars.js'), 'utf8') },
]

const check = process.argv.includes('--check')
let stale = 0
for (const { out, build } of copies) {
  const next = build()
  if (check) {
    if (!existsSync(out) || readFileSync(out, 'utf8') !== next) {
      console.error(`out of date: ${out}`)
      stale++
    }
  } else {
    writeFileSync(out, next)
    console.log(`wrote ${out}`)
  }
}
if (stale) process.exit(1)
